export function LegalView({ document }: { document: 'privacy' | 'consent' }) {
  useEffect(() => {
    const previous = window.document.title
    window.document.title =
      document === 'privacy'
        ? 'Политика обработки персональных данных — CoffeDzhim.ru'
        : 'Согласие на обработку персональных данных — CoffeDzhim.ru'
    return () => {
      window.document.title = previous
    }
  }, [document])

  return document === 'privacy' ? <PrivacyDocument /> : <ConsentDocument />
}
