function noticeClosed() {
  try {
    return localStorage.getItem(PRIVACY_NOTICE_KEY) === CONSENT_VERSION
  } catch {
    return false
  }
}

export function PrivacyNotice() {
  const [visible, setVisible] = useState(() => !noticeClosed())

  if (!visible) return null

  const close = () => {
    try {
      localStorage.setItem(PRIVACY_NOTICE_KEY, CONSENT_VERSION)
    } catch {
      // Окно закроется до конца этого визита, даже если браузер запретил запись.
    }
    setVisible(false)
  }

  return createPortal(
    <div
      className="privacy-notice"
      role="dialog"
      aria-modal="false"
      aria-labelledby="privacy-notice-title"
    >
      <div>
        <p className="privacy-notice__title" id="privacy-notice-title">
          Персональные данные
        </p>
        <p id="privacy-notice-text">
          Сайт собирает имя, телефон и, если вы сами укажете, Telegram или email
          только в момент отправки заявки. Заявка хранится на сервере и
          передаётся менеджеру в Telegram. Счётчиков и рекламных cookie нет.
          Кнопка «Понятно» только закрывает это окно и не заменяет согласие:
          его нужно отметить в форме.{' '}
          <a href="#privacy">Политика</a>
          {' · '}
          <a href="#consent">Согласие</a>
        </p>
      </div>
      <button className="button button--dark" type="button" onClick={close}>
        Понятно
      </button>
    </div>,
    document.body,
  )
}

